#!/usr/bin/env python3
"""
mkStubs.py — Generate Ndless syscall C/C++ declarations and ARM SWI stub wrappers.

Parses annotated `#define e_<name> <id> // <rettype> <func>(<args>)` entries
between `START_OF_LIST` and `END_OF_LIST` in `syscall-list.h` and generates:
  1. `syscall-decls.h`: C/C++ function prototypes for all OS syscalls.
  2. `stubs.cpp`:
     - Template `syscall<e_id, RetType>(p1, ...)` wrappers for functions taking
       4 or fewer register arguments without variadic (`...`) parameters.
     - `__attribute__((naked))` inline-assembly wrappers that preserve `lr` on
       `savedlr_stack` across `swi` traps for functions with 5+ or variadic arguments.
"""

import os
import re
import sys
from typing import List, Tuple

# Header prologue/epilogue for generated syscall-decls.h
DECLS_HEADER = """#ifndef SYSCALL_DECLS
#define SYSCALL_DECLS

//This file has been autogenerated my mkStubs.py

#ifdef __cplusplus
extern "C" {
#endif // __cplusplus

#include <stddef.h>
#include <stdint.h>
#include <string.h>
#include <ngc.h>
#include <nucleus.h>
#include <lualib.h>
#include <lauxlib.h>
#include <bsdcompat.h>
#include <usb.h>

"""

DECLS_FOOTER = """
#ifdef __cplusplus
}
#endif // __cplusplus

#endif // !SYSCALL_DECLS
"""

# Source prologue/epilogue for generated stubs.cpp
STUBS_HEADER = """#include <syscall-decls.h>
#include <syscall-list.h>
#include <syscall.h>

//This file has been autogenerated my mkStubs.py

extern "C" {
int savedlr_stack[10];
int savedlr_stack_nr = 0;

"""

STUBS_FOOTER = "}\n"

# Matches lines of the form:
#   #define e_foo 123 // int foo(int p1, int p2)
#   #define e_bar 124 // (const char*) bar (int p1)
SYSCALL_DEFINE_PATTERN = re.compile(
    r"^#define\s+(e_\w+)\s+\d+\s+//\s+(([^ (]+)|\((.+?)\))\s+(\w+)\s*\((.*?)\)$"
)


def resolve_paths(argv: List[str]) -> Tuple[str, str, str]:
    """
    Determine input (`syscall-list.h`) and output (`syscall-decls.h`, `stubs.cpp`)
    paths from CLI arguments, or fall back to relative SDK paths.
    """
    if len(argv) < 4:
        base_dir = os.path.dirname(os.path.abspath(__file__))
        syscall_list_path = os.path.join(base_dir, "../../ndless-sdk/include/syscall-list.h")
        syscall_decls_path = os.path.join(base_dir, "../../ndless-sdk/include/syscall-decls.h")
        stubs_cpp_path = os.path.join(base_dir, "../../ndless-sdk/libsyscalls/stubs.cpp")
    else:
        syscall_list_path = argv[1]
        syscall_decls_path = argv[2]
        stubs_cpp_path = argv[3]
    return syscall_list_path, syscall_decls_path, stubs_cpp_path


def format_stub(enum_name: str, rettype: str, func_name: str, args_str: str) -> str:
    """
    Build the C++ stub definition for a single syscall entry.

    Uses the inline C++ `syscall<ID, Ret>(...)` template when arguments fit in
    ARM registers r0-r3 (<= 4 non-variadic arguments), or a naked assembly
    trampoline with an LR save stack when stack arguments or variadics are used.
    """
    if not args_str.strip():
        param_count = 0
    else:
        param_count = args_str.count(", ") + 1

    if param_count <= 4 and "..." not in args_str:
        param_list = [f"p{p}" for p in range(1, param_count + 1)]
        param_str = ",".join(param_list)
        return (
            f"{rettype} {func_name}({args_str})\n"
            "{\n"
            f"\treturn syscall<{enum_name}, {rettype}>({param_str});\n"
            "}\n\n"
        )

    return (
        f"__attribute__((naked)) {rettype} {func_name}({args_str})\n"
        "{\n"
        '\tasm volatile("push {r4-r6}\\n"\n'
        '\t\t\t\t"ldr r4, =savedlr_stack\\n"\n'
        '\t\t\t\t"ldr r5, =savedlr_stack_nr\\n"\n'
        '\t\t\t\t"ldr r6, [r5]\\n"\n'
        '\t\t\t\t"add r6, r6, #1\\n"\n'
        '\t\t\t\t"str lr, [r4, r6, lsl #2]\\n"\n'
        '\t\t\t\t"str r6, [r5]\\n"\n'
        '\t\t\t\t"pop {r4-r6}\\n"\n'
        '\t\t\t\t"swi %[nr]\\n"\n'
        '\t\t\t\t"push {r4-r6}\\n"\n'
        '\t\t\t\t"ldr r4, =savedlr_stack\\n"\n'
        '\t\t\t\t"ldr r5, =savedlr_stack_nr\\n"\n'
        '\t\t\t\t"ldr r6, [r5]\\n"\n'
        '\t\t\t\t"ldr lr, [r4, r6, lsl #2]\\n"\n'
        '\t\t\t\t"sub r6, r6, #1\\n"\n'
        '\t\t\t\t"str r6, [r5]\\n"\n'
        '\t\t\t\t"pop {r4-r6}\\n"\n'
        '\t\t\t\t"bx lr\\n"\n'
        f'\t\t\t\t".ltorg" :: [nr] "i" ({enum_name}));\n'
        "}\n\n"
    )


def main() -> None:
    # --------------------------------------------------------------------------
    # Step 1: Resolve file paths and read syscall-list.h
    # --------------------------------------------------------------------------
    syscall_list_path, syscall_decls_path, stubs_cpp_path = resolve_paths(sys.argv)

    try:
        with open(syscall_list_path, "r", encoding="utf-8") as f:
            lines = f.readlines()
    except OSError as e:
        sys.stderr.write(f"Couldn't open syscall-list.h: {e}\n")
        sys.exit(1)

    # --------------------------------------------------------------------------
    # Step 2: Locate the START_OF_LIST marker in syscall-list.h
    # --------------------------------------------------------------------------
    start_idx = -1
    for idx, line in enumerate(lines):
        if "START_OF_LIST" in line:
            start_idx = idx + 1
            break

    if start_idx == -1:
        sys.stderr.write("START_OF_LIST not found in syscall-list.h\n")
        sys.exit(1)

    # --------------------------------------------------------------------------
    # Step 3: Ensure output directories exist
    # --------------------------------------------------------------------------
    for output_file in (stubs_cpp_path, syscall_decls_path):
        output_dir = os.path.dirname(os.path.abspath(output_file))
        if output_dir and not os.path.exists(output_dir):
            os.makedirs(output_dir, exist_ok=True)

    # --------------------------------------------------------------------------
    # Step 4: Parse syscall definitions and emit declarations and stubs
    # --------------------------------------------------------------------------
    with (
        open(stubs_cpp_path, "w", encoding="utf-8") as stubs_f,
        open(syscall_decls_path, "w", encoding="utf-8") as decls_f,
    ):
        decls_f.write(DECLS_HEADER)
        stubs_f.write(STUBS_HEADER)

        for raw_line in lines[start_idx:]:
            stripped = raw_line.strip()
            if "END_OF_LIST" in stripped:
                break

            match = SYSCALL_DEFINE_PATTERN.match(stripped)
            if not match:
                continue

            enum_name = match.group(1)
            rettype = match.group(3) if match.group(3) else match.group(4)
            func_name = match.group(5)
            args_str = match.group(6)

            stubs_f.write(format_stub(enum_name, rettype, func_name, args_str))
            decls_f.write(f"{rettype} {func_name}({args_str});\n")

        stubs_f.write(STUBS_FOOTER)
        decls_f.write(DECLS_FOOTER)

    print("Stubs generated successfully.")


if __name__ == "__main__":
    main()
